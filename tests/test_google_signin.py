def fail(code):
    return ClientError({"Error": {"Code": code, "Message": "x"}}, "Op")


class FakeSSM:
    def get_parameter(self, Name, WithDecryption):
        return {"Parameter": {"Value": json.dumps({"client_id": "g.apps.googleusercontent.com", "client_secret": "GOCSPX-x"})}}


class FakeCognito:
    def __init__(self):
        self.calls, self.clients, self.mapping_updates, self.pools, self.providers = [], {}, [], 0, []
        self.broken = None

    def create_user_pool(self, **kw):
        self.pools += 1
        return {"UserPool": {"Id": "us-east-1_POOL"}}

    def create_user_pool_domain(self, **kw):
        pass

    def create_identity_provider(self, **kw):
        self.providers.append(kw)

    def update_identity_provider(self, **kw):
        if self.broken:
            raise fail(self.broken)
        self.mapping_updates.append(kw)

    def create_user_pool_client(self, UserPoolId, **kw):
        if self.broken:
            raise fail(self.broken)
        self.made = getattr(self, "made", 0) + 1
        cid = f"client-portal-{self.made}"
        self.clients[cid] = kw
        self.calls.append(("create", cid))
        return {"UserPoolClient": {"ClientId": cid}}

    def delete_user_pool_client(self, UserPoolId, ClientId):
        self.calls.append(("delete", ClientId))
        if ClientId not in self.clients:
            raise fail("ResourceNotFoundException")
        del self.clients[ClientId]


