"""Generates the files that come from the settings registry (config/settings.json).

    python tools/gen_settings.py            write lambda/platform_settings_data.py and docs/SETTINGS.md
    python tools/gen_settings.py --check    change nothing; exit 1 if either file is out of date

The registry is the one place every platform setting is described (see docs/SETTINGS_PLAN.md). Edit config/settings.json, then run this."""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
REGISTRY = os.path.join(ROOT, "config", "settings.json")
DATA = os.path.join(ROOT, "lambda", "platform_settings_data.py")
DOCS = os.path.join(ROOT, "docs", "SETTINGS.md")


def load():
    with open(REGISTRY, encoding="utf8") as handle:
        return json.load(handle)


def py(value):
    """A Python literal for a JSON value."""
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(py(v) for v in value) + "]"
    raise TypeError(value)


def kind(setting):
    if "type" in setting:
        return setting["type"]
    default = setting["default"]
    return "float" if isinstance(default, float) else "int" if isinstance(default, int) else "text"


def render_data(registry):
    lines = [
        "# Generated by tools/gen_settings.py from config/settings.json. Do not edit: change the registry and run the tool.",
        '"""The shipped defaults and ranges of every platform setting (see platform_settings.py)."""',
        "",
        "SETTINGS = {",
    ]
    for setting in registry["settings"]:
        lines.append(
            f'    {json.dumps(setting["key"])}: {{"type": {py(kind(setting))}, "default": {py(setting["default"])}, "min": {py(setting.get("min"))}, '
            f'"max": {py(setting.get("max"))}, "env": {py(setting.get("env"))}}},'
        )
    lines += ["}", ""]
    return "\n".join(lines)


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def number(value):
    if isinstance(value, float) and value == int(value) and abs(value) >= 1:
        return f"{int(value):,}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def range_text(setting):
    if setting.get("choices"):
        return ", ".join(str(c) for c in setting["choices"])
    lo, hi = setting.get("min"), setting.get("max")
    if lo is None and hi is None:
        return "any"
    return f"{number(lo) if lo is not None else '..'} to {number(hi) if hi is not None else '..'}"


def render_docs(registry):
    groups = registry["groups"]
    by_group = {}
    for setting in registry["settings"]:
        by_group.setdefault(setting["group"], []).append(setting)
    out = [
        "# Platform settings (reference)",
        "",
        "<!-- Generated by tools/gen_settings.py from config/settings.json. Do not edit by hand: change the registry and run  python tools/gen_settings.py  -->",
        "",
        f"Every number the platform uses as a limit, a default or a time lives in **one registry**: [`config/settings.json`](../config/settings.json). This page is generated from it ({len(registry['settings'])} settings in {len(groups)} groups), so it is always current. The reasoning is in [SETTINGS_PLAN.md](SETTINGS_PLAN.md).",
        "",
        "## How to read it",
        "",
        "| Column | Meaning |",
        "|---|---|",
        "| **Default** | The value the platform ships with. Nothing changes until someone changes it |",
        "| **Range** | The lowest and highest value that makes sense. From plan step S2 the platform refuses anything outside it; today it is the documented safe range |",
        "| **Scope** | `runtime`: read by the platform's own code (changeable without redeploying the AWS stack once S2 exists); `deploy`: part of the AWS stack (change it with the install tool, then `plan` and `apply`) |",
        "| **Risk** | `low`, `careful` (can raise the AWS bill or affect capacity) or `security` (changes who can get in and for how long) |",
        "",
        "## How to change a setting today",
        "",
        "1. **`deploy` settings** that are template parameters (for example `gateway.inflightGlobal`): pass them to the install tool or edit the parameter default in `template.yaml`, then `plan` and `apply`.",
        "2. **`runtime` settings:** change the `default` in `config/settings.json`, run `python tools/gen_settings.py`, run the tests, and publish the update (`node setup.mjs upgrade`).",
        "3. A portal page and a command that change runtime settings without touching code are the next steps of the plan (S2 and S3).",
        "",
        "A test (`tests/test_settings.py`) makes sure this registry, the code and the CloudFormation template agree, and that no new number is added to the code without being added here.",
        "",
    ]
    for group in groups:
        rows = by_group.get(group["id"], [])
        if not rows:
            continue
        out += [f"## {group['title']}", "", group["help"], "", "| Setting | Default | Range | Scope | Risk | What it does |", "|---|---|---|---|---|---|"]
        for s in rows:
            unit = f" {s['unit']}" if s.get("unit") and s["unit"] not in ("model name",) else ""
            default = s["default"] if s["default"] != "" else "(empty)"
            more = ""
            if s.get("cost"):
                more += f" **Cost:** {s['cost']}"
            if s.get("note"):
                more += f" {s['note']}"
            out.append(f"| `{s['key']}`<br>{cell(s['title'])} | {cell(number(default) if not isinstance(default, str) else default)}{cell(unit)} | {cell(range_text(s))} | {s['scope']} | {s['risk']} | {cell(s['help'] + more)} |")
        out.append("")
    out += ["## Kept in code on purpose", "", "These numbers are not settings: they are units, facts from a provider, or values that follow another setting.", "", "| Where | Why it is not a setting |", "|---|---|"]
    for item in registry["fixed"]:
        out.append(f"| `{item['code']}` | {cell(item['reason'])} |")
    out.append("")
    return "\n".join(out)


def main(argv):
    registry = load()
    wanted = {DATA: render_data(registry), DOCS: render_docs(registry)}
    stale = []
    for path, text in wanted.items():
        current = open(path, encoding="utf8").read().replace("\r\n", "\n") if os.path.exists(path) else None
        if current != text:
            stale.append(os.path.relpath(path, ROOT))
            if "--check" not in argv:
                with open(path, "w", encoding="utf8", newline="\n") as handle:
                    handle.write(text)
    if "--check" in argv:
        if stale:
            print("out of date: " + ", ".join(stale) + "  (run: python tools/gen_settings.py)")
            return 1
        print("settings files are up to date")
        return 0
    print("written: " + (", ".join(stale) if stale else "nothing changed"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
